"""Reviewed Tk Studio visual baselines and real before/after reports.

Candidate screenshots are generated by CI, compared against *manually approved*
reference PNGs from the repository. A candidate is NEVER approved by capture,
comparison, or a CI token. Missing baselines are "review_required", not "pass".
All code paths stay Pillow-only; Qt is not a dependency.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
from hashlib import sha256
from html import escape
import json
from pathlib import Path
import re
import shutil

EXPECTED = (
    "01-studio-2d-textures-autotiles",
    "02-studio-2d-grid",
    "03-studio-iso",
    "04-studio-playtest",
)
PROFILE = "tk-linux-xvfb-1280x850"
SCHEMA = "drawtemp-tk-goldens-v1"
DEFAULT_REFERENCES = (Path(__file__).resolve().parents[1]
                      / "tests_standalone/goldens/studio-tk")
MAX_CHANNEL_DELTA = 12
MAX_CHANGED_FRACTION = 0.005
_SAFE_SHA = re.compile(r"[0-9a-f]{64}\Z")


def _hash(path):
    return sha256(Path(path).read_bytes()).hexdigest()


def _write_json(path, data):
    p = Path(path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(data, indent=2, ensure_ascii=False,
                            sort_keys=True) + "\n", encoding="utf-8")


def _checked_image(directory, name, sha):
    if name not in EXPECTED or not isinstance(sha, str) or not _SAFE_SHA.fullmatch(sha):
        raise ValueError("Unsafe visual reference entry")
    path = Path(directory) / (name + ".png")
    if not path.is_file() or path.is_symlink():
        raise FileNotFoundError(f"Required PNG missing: {path}")
    if _hash(path) != sha:
        raise ValueError("Visual reference hash mismatch: " + str(path))
    return path


def _candidate(folder):
    root = Path(folder)
    data = json.loads((root / "manifest.json").read_text(encoding="utf-8"))
    if (data.get("schema") != "drawtemp-studio-pr-visual-v1" or
            data.get("capture") != "real Tk window via X11 ImageGrab" or
            data.get("mission") != "fortified_village_3717a" or
            not isinstance(data.get("frames"), list) or
            len(data["frames"]) != len(EXPECTED)):
        raise ValueError("Missing, incomplete or unverifiable real Tk capture")
    frames = {}
    for entry in data["frames"]:
        name = entry.get("name")
        if (name not in EXPECTED or name in frames or
                entry.get("file") != name + ".png" or
                type(entry.get("canvas_items")) is not int or
                entry["canvas_items"] < 50 or
                not isinstance(entry.get("map_luma_stddev"), (int, float)) or
                entry["map_luma_stddev"] <= 8):
            raise ValueError("Unverified screenshot metadata")
        _checked_image(root, name, entry.get("image_sha256"))
        frames[name] = entry
    if set(frames) != set(EXPECTED):
        raise ValueError("Incomplete visual capture scenarios")
    return data, frames


def load_reference(refs=DEFAULT_REFERENCES):
    """Missing approvals are allowed but tampering is a hard failure."""
    directory = Path(refs) / PROFILE
    path = directory / "manifest.json"
    if not path.exists():
        return None
    data = json.loads(path.read_text("utf-8"))
    if (data.get("schema") != SCHEMA or data.get("profile") != PROFILE or
            data.get("reviewed") is not True or
            not isinstance(data.get("reviewer"), str) or
            not data["reviewer"].strip() or
            not isinstance(data.get("files"), dict) or
            set(data["files"]) != set(EXPECTED)):
        raise ValueError("Golden manifest invalid, unreviewed or incomplete")
    for name, metadata in data["files"].items():
        if (not isinstance(metadata, dict) or
                type(metadata.get("width")) is not int or
                type(metadata.get("height")) is not int or
                metadata["width"] != 1280 or metadata["height"] != 850):
            raise ValueError("Approved screenshot geometry mismatch: " + name)
        _checked_image(directory, name, metadata.get("sha256"))
    return data


def approve(candidate, refs=DEFAULT_REFERENCES, *, reviewer):
    """Offline manual action, never invoked by GitHub Actions."""
    if not isinstance(reviewer, str) or not reviewer.strip():
        raise ValueError("A named human reviewer is required")
    folder = Path(candidate)
    _, frames = _candidate(folder)
    directory = Path(refs) / PROFILE
    if (directory / "manifest.json").exists():
        raise FileExistsError("Golden reference exists; replace through a separate reviewed PR")
    from PIL import Image

    approved = {}
    # Prevalidate ALL candidates before writing a single approved file.
    for name in EXPECTED:
        with Image.open(folder / (name + ".png")) as image:
            if image.size != (1280, 850):
                raise ValueError("Golden must be an actual 1280x850 Studio capture")
        approved[name] = {
            "width": 1280, "height": 850,
            "sha256": frames[name]["image_sha256"],
        }
    directory.mkdir(parents=True, exist_ok=True)
    for name in EXPECTED:
        shutil.copyfile(folder / (name + ".png"), directory / (name + ".png"))
    manifest = {
        "schema": SCHEMA, "profile": PROFILE, "reviewed": True,
        "reviewer": reviewer.strip(),
        "approved_utc": datetime.now(timezone.utc).isoformat(),
        "source_mission": "fortified_village_3717a",
        "files": approved,
        "tolerance": {"max_channel_delta": MAX_CHANNEL_DELTA,
                      "max_changed_fraction": MAX_CHANGED_FRACTION},
    }
    _write_json(directory / "manifest.json", manifest)
    return directory / "manifest.json"


def image_diff(before_path, after_path, diff_path, comparison_path):
    """Per-channel threshold + visual red heatmap and a three-panel collage."""
    from PIL import Image, ImageChops, ImageDraw, ImageStat

    with Image.open(before_path) as old, Image.open(after_path) as new:
        before, after = old.convert("RGBA"), new.convert("RGBA")
    if before.size != after.size:
        raise ValueError("Reference and current screenshots differ in size")
    if before.size != (1280, 850):
        raise ValueError("Unexpected screenshot dimensions")
    difference = ImageChops.difference(before, after)
    # Each pixel counts once if ANY channel exceeds the configured tolerance.
    limit = MAX_CHANNEL_DELTA
    # Combine the four per-channel differences by per-pixel maximum. A single
    # red/green/blue/alpha channel regression must still be counted.
    r, g, b, alpha = difference.split()
    mask = ImageChops.lighter(
        ImageChops.lighter(r, g), ImageChops.lighter(b, alpha)).point(
            lambda value: 255 if value > limit else 0)
    changed = int(ImageStat.Stat(mask).sum[0] / 255)
    pixel_count = before.width * before.height
    frac = changed / pixel_count
    maximum = max(channel.getextrema()[1] for channel in difference.split())
    heat = Image.new("RGB", before.size, "#131e31")
    heat.paste("#ff3258", mask=mask)
    diff_path = Path(diff_path)
    comparison_path = Path(comparison_path)
    diff_path.parent.mkdir(parents=True, exist_ok=True)
    comparison_path.parent.mkdir(parents=True, exist_ok=True)
    heat.save(diff_path)
    # Both frames are untouched pixel copies; labels occupy a separate header.
    collage = Image.new("RGB", (1280 * 3, 850 + 52), "#eef2f7")
    for index, (label, frame) in enumerate((
            ("AVANT - reference approuvee", before),
            ("APRES - capture de la PR", after),
            ("DIFF - ecarts visibles", heat))):
        x = index * 1280
        collage.paste(frame.convert("RGB"), (x, 52))
        ImageDraw.Draw(collage).text((x + 20, 16), label, fill="#1b263b")
    collage.save(comparison_path)
    return {
        "changed_pixels": changed, "total_pixels": pixel_count,
        "changed_fraction": round(frac, 8),
        "max_channel_delta": maximum,
        "passed": frac <= MAX_CHANGED_FRACTION,
        "threshold": {"max_channel_delta": limit,
                      "max_changed_fraction": MAX_CHANGED_FRACTION},
    }


def review(candidate, refs=DEFAULT_REFERENCES, *, require_approved=False):
    root = Path(candidate)
    _, frames = _candidate(root)
    reference = load_reference(refs)
    output = {"schema": SCHEMA, "profile": PROFILE,
              "reference_approved": reference is not None,
              "result": "review_required", "cases": {}}
    for name in EXPECTED:
        after = root / (name + ".png")
        case = {"file": name + ".png", "status": "review_required"}
        if reference:
            source = _checked_image(Path(refs) / PROFILE, name,
                                    reference["files"][name]["sha256"])
            prior = root / "approved" / (name + ".png")
            prior.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, prior)
            metrics = image_diff(
                prior, after, root / "diff" / (name + ".png"),
                root / "comparisons" / (name + ".png"))
            case.update(status="pass" if metrics["passed"] else "fail",
                        metrics=metrics)
        output["cases"][name] = case
    if reference:
        output["result"] = ("pass" if all(
            c["status"] == "pass" for c in output["cases"].values()) else "fail")
    _write_json(root / "visual-review.json", output)
    def picture(path, label):
        if not (root / path).is_file():
            return "<em>Non disponible : référence non encore approuvée</em>"
        return (f'<a href="{escape(path)}"><img loading="lazy"'
                f' src="{escape(path)}" alt="{escape(label)}"></a>')
    rows = []
    for name, case in output["cases"].items():
        rows.append(
            f'<section><h2>{escape(name)} — {escape(case["status"])}</h2>'
            '<div class="comparison">'
            + '<figure><figcaption>Avant — référence approuvée</figcaption>'
            + picture("approved/" + name + ".png", "Référence") + '</figure>'
            + '<figure><figcaption>Après — capture actuelle</figcaption>'
            + picture(name + ".png", "Actuel") + '</figure>'
            + '<figure><figcaption>Différences</figcaption>'
            + picture("diff/" + name + ".png", "Différences") + '</figure>'
            + '</div>'
            + '<p>Pixels modifiés : '
            + escape(str(case.get("metrics", {}).get("changed_fraction", "N/A")))
            + '</p></section>')
    explanation = ("Références contrôlées et comparaison disponible."
                   if reference else
                   "Aucune référence approuvée : captures candidates uniquement. "
                   "Un humain doit d’abord examiner puis approuver les PNG.")
    html = (
        '<!doctype html><html lang="fr"><meta charset="utf-8">'
        '<title>DrawTemp Studio — visual review</title>'
        '<style>body{margin:24px auto;padding:0 18px;max-width:1650px;'
        'font:15px system-ui;background:#f0f3f7;color:#142438}'
        'section{margin:18px 0;padding:18px;background:white;border-radius:10px}'
        '.comparison{display:grid;grid-template-columns:repeat(3,minmax(0,1fr));'
        'gap:12px}figure{margin:0;min-width:0}img{width:100%;height:auto;'
        'border:1px solid #ccd4df}figcaption{font-weight:bold;margin-bottom:9px}'
        '</style><h1>DrawTemp — contrôle visuel avant / après</h1>'
        f'<p>{escape(explanation)}</p>'
        f'<p>Statut : <strong>{escape(output["result"])}</strong>. '
        'Linux/Xvfb : les résultats ne certifient pas le rendu Windows.</p>'
        + "".join(rows) + '</html>')
    (root / "index.html").write_text(html, encoding="utf-8")
    if output["result"] == "fail" or (require_approved and reference is None):
        return 1
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    check = sub.add_parser("compare", help="Compare to independently approved references")
    check.add_argument("--capture", type=Path, required=True)
    check.add_argument("--goldens", type=Path, default=DEFAULT_REFERENCES)
    check.add_argument("--require-approved", action="store_true")
    approval = sub.add_parser("approve", help="Human-reviewed, offline approval")
    approval.add_argument("--capture", type=Path, required=True)
    approval.add_argument("--goldens", type=Path, default=DEFAULT_REFERENCES)
    approval.add_argument("--reviewer", required=True)
    args = parser.parse_args(argv)
    if args.command == "approve":
        print("Approved manifest: " + str(
            approve(args.capture, args.goldens, reviewer=args.reviewer)))
        return 0
    result = review(args.capture, args.goldens, require_approved=args.require_approved)
    print(json.dumps(json.loads(
        (args.capture / "visual-review.json").read_text(encoding="utf-8")),
        ensure_ascii=False))
    return result


if __name__ == "__main__":
    raise SystemExit(main())
